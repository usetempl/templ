import { createRequire } from "node:module";
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import process from "node:process";
import { fileURLToPath, URL } from "node:url";
import { FEATURE_LIMITS } from "../../../packages/chat/src/feature-limits.ts";
import { generateWidgetColors } from "./generate-widget-colors.mjs";
import {
  WIDGET_BUDGET,
  WIDGET_CHUNK_BUDGET,
  WIDGET_CHUNKS,
  WIDGET_SUPPORT_DAYS,
  addWidgetBuild,
  assertWidgetBudget,
  measureWidget,
  pruneWidgetBuilds,
  widgetManifestProblem,
} from "./widget-budget.mjs";
const require = createRequire(import.meta.url);
generateWidgetColors(
  process.argv.includes("--check") || process.argv.includes("--measure"),
);
const runtime = createRequire(require.resolve("wrangler/package.json"));
const { build } = runtime("esbuild");
const path = (relative) => fileURLToPath(new URL(relative, import.meta.url));
const lib = path("../src/lib/");
const source = `${lib}support-widget.ts`;
const target = path("../public/support-widget.js");
const typesTarget = path("../public/support-widget.d.ts");
const types =
  "// Generated from src/widget/support-widget.d.ts. Do not edit this file.\n" +
  readFileSync(path("../src/widget/support-widget.d.ts"), "utf8");
/** Immutable copies, one per build: `/support-widget/<id>.js`, and the
 * chunks each one loads: `/support-widget/<chunk>-<id>.js`. */
const versionsDir = path("../public/support-widget/");
const manifestPath = `${lib}support-widget-versions.json`;
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const sha384 = (bytes) => createHash("sha384").update(bytes).digest("base64");

const digest = sha256(readFileSync(source));
/** One minified ES module in UTF-8; the demo renderer stays out of every
 * file. Chunk builds set the chunk names too, so what they import is bundled
 * plainly rather than lazily. */
const bundle = async (contents, define = {}, banner) =>
  (
    await build({
      stdin: { contents, resolveDir: lib, loader: "ts" },
      bundle: true,
      format: "esm",
      target: "es2020",
      minify: true,
      charset: "utf8",
      write: false,
      plugins: [
        {
          name: "widget-feature-limits",
          setup(build) {
            // The generated color module holds literal constants only.
            build.onResolve(
              { filter: /^\.\/support-widget-(?:colors|theme|appearance)$/ },
              ({ path }) => ({
                path: `${lib}${path.slice(2)}.ts`,
                sideEffects: false,
              }),
            );
            build.onLoad(
              { filter: /support-widget-(?:ops|check|member)\.ts$/ },
              ({ path }) => ({
                loader: "ts",
                contents: readFileSync(path, "utf8")
                  .replace(/FEATURE_LIMITS\.([A-Za-z0-9_]+)/g, (_, key) => {
                    if (!(key in FEATURE_LIMITS))
                      throw new Error(`Unknown widget limit: ${key}`);
                    return JSON.stringify(FEATURE_LIMITS[key]);
                  }),
              }),
            );
          },
        },
      ],
      define: {
        __TEMPL_WIDGET_DRAFTS__: '"drafts"',
        __TEMPL_WIDGET_CARD__: '"card"',
        __TEMPL_WIDGET_CONTEXT__: '"context"',
        __TEMPL_WIDGET_MEMBER__: '"member"',
        __TEMPL_WIDGET_EXTRAS__: '"extras"',
        __TEMPL_WIDGET_EVM__: '"evm"',
        __TEMPL_WIDGET_SOLANA__: '"solana"',
        __TEMPL_WIDGET_LIVE__: '"live"',
        // The verified-domain line and member screenshots.
        __TEMPL_WIDGET_OPS__: '"ops"',
        __TEMPL_WIDGET_DOMAIN__: '"domain"',
        __TEMPL_WIDGET_MEDIA__: '"media"',
        ...define,
      },
      ...(banner ? { banner: { js: banner } } : {}),
    })
  ).outputFiles[0].text;
/** The manifest names the source of every chunk; they carry no banner. */
// Dependencies can build first; the manifest retains its canonical chunk order.
const chunks = Object.fromEntries(WIDGET_CHUNKS.map((name) => [name, null]));
const chunkBytes = {};
for (const [name, contents] of Object.entries({
  appearance:
    'export { bindWidgetAppearance, FRAME_STYLE } from "./support-widget-appearance";',
  drafts: 'export { save, read, canPersist, pending } from "./support-widget-drafts";',
  style: 'export { widgetStyle } from "./support-widget-style";',
  lead: 'export { lead, forms } from "./support-widget-lead";',
  // The context card, with only the context rules it uses. The context
  // chunk checks the typed details' networks with the same rules.
  card: `import { parseSupportNetwork, parseTransactionReference, supportNetworkName } from "@templ/chat/support-context";
import { contextCard } from "./support-widget";
export const rules = { parseSupportNetwork, parseTransactionReference, supportNetworkName };
export const card = (widget) => contextCard(widget, rules);`,
  // The typed details from the app, beside the context card,
  // which this chunk loads.
  details: 'export * from "./support-widget-details";',
  appParser:
    'export { parseAppContext, SUPPORT_DIAGNOSTIC_FIELDS } from "@templ/chat/support-app-context";',
  diagnostics:
    'export { diagnostics, picker, allowed } from "./support-widget-diagnostics";',
  context:
    'export { card, details, failureControls } from "./support-widget-context";',
  snapshot: 'export { card } from "./support-widget-snapshot";',
  // A member's screenshot, checked and sent; the member
  // lines load it from the Add screenshot button.
  media: 'export { button, media } from "./support-widget-media";',
  // Optional reply notices load before the member lines that may offer them.
  guest:
    'export { guest, framePage, replyEmail } from "./support-widget-guest";',
  // The wait, follow-up, sources and shared details under a thread.
  member: 'export { member } from "./support-widget-member";',
  // The install check, which the ops chunk loads only on a check link.
  check: 'export { check } from "./support-widget-check";',
  // The key warning before a send and the consent to share an action's
  // result, which the consent chunk loads when a page or a draft needs them.
  ops: 'export { ops } from "./support-widget-ops";',
  // The summary before a send, the empty chat's two questions, links in
  // messages and the lines that say a person from the team joined.
  consent: 'export { consent, leadStyles } from "./support-widget-consent";',
  // What the member sees after a send (Received, the AI agent typing with
  // Talk to a person, the wait and handoff lines, and the Verify wallet
  // card), and the Sign in again card.
  conversation: 'export { chatFirstControls } from "./support-widget-chat-first";',
  "conversation-style": 'export { CONVERSATION_STYLE } from "./support-widget-chat-style";',
  "drawer-style": 'export { drawerStyle } from "./support-widget-drawer-style";',
  "drawer-notices": 'export { drawerNotices } from "./support-widget-drawer-notices";',
  "drawer-wallet": 'export { drawerWallet } from "./support-widget-drawer-wallet";',
  drawer: 'export { prepareDrawer } from "./support-widget-drawer";',
  conversations: 'export { conversationDrawer, memberConversations, memberConversationsPath, bindMemberHistory, classicMemberHistory } from "./support-widget-conversations";',
  welcome: 'export { welcome } from "./support-widget-welcome";',
  art: 'export { art, mount, bindWidgetBranding } from "./support-widget-art";',
  extras: 'export { extras } from "./support-widget";',
  // Each wallet family's sign-in, loaded only for a page with that wallet:
  // an EIP-1193 provider, or a Solana wallet.
  evm: 'export { evmKit as evm } from "./support-widget";',
  // The Solana one carries the signature encoding.
  solana: `import { encodeWidgetSolanaSignature } from "@templ/chat/widget-wallet";
import { solanaKit } from "./support-widget";
export const solana = (wallet) =>
  solanaKit(wallet, { encodeWidgetSolanaSignature });`,
  // The visitor check's frame, loaded by the live chunk
  // only for a new guest of a workspace that turned the check on.
  turnstile: 'export { check } from "./support-widget-turnstile";',
  encrypted: 'export { secure, route } from "./support-widget-encrypted";',
  // This tab's session after a reload, the waiting marker,
  // remembered sign-in, the member socket and the visitor check's loader.
  live: 'export { live, newCase } from "./support-widget-live";',
  // The verified-domain line under the title, loaded
  // only when the workspace's policy names a domain.
  domain: 'export { domain } from "./support-widget-domain";',
})) {
  // A chunk that loads another names it: the context chunk the card, the
  // extras the member lines, the member lines the screenshot and the live
  // chunk the visitor check.
  const loads = {
    context: {
      __TEMPL_WIDGET_CARD__: "card",
      __TEMPL_WIDGET_DETAILS__: "details",
      __TEMPL_WIDGET_APP_PARSER__: "appParser",
      __TEMPL_WIDGET_DIAGNOSTICS__: "diagnostics",
    },
    snapshot: { __TEMPL_WIDGET_CONTEXT__: "context" },
    member: {
      __TEMPL_WIDGET_GUEST__: "guest",
      __TEMPL_WIDGET_MEDIA__: "media",
      __TEMPL_WIDGET_CONTEXT__: "context",
    },
    extras: {
      __TEMPL_WIDGET_MEMBER__: "member",
      __TEMPL_WIDGET_WELCOME__: "welcome",
      __TEMPL_WIDGET_GUEST__: "guest",
    },
    live: { __TEMPL_WIDGET_TURNSTILE__: "turnstile", __TEMPL_WIDGET_ENCRYPTED__: "encrypted" },
    ops: { __TEMPL_WIDGET_CHECK__: "check" },
    consent: { __TEMPL_WIDGET_OPS__: "ops" },
    drawer: {
      __TEMPL_WIDGET_DRAWER_STYLE__: "drawer-style",
      __TEMPL_WIDGET_DRAWER_NOTICES__: "drawer-notices",
      __TEMPL_WIDGET_DRAWER_WALLET__: "drawer-wallet",
    },
    welcome: {
      __TEMPL_WIDGET_CONVERSATION__: "conversation",
      __TEMPL_WIDGET_CONVERSATION_STYLE__: "conversation-style",
      __TEMPL_WIDGET_DRAWER__: "drawer",
      __TEMPL_WIDGET_CONVERSATIONS__: "conversations",
    },
  }[name];
  const text = await bundle(
    contents,
    Object.fromEntries(
      Object.entries(loads ?? {}).map(([key, loaded]) => [
        key,
        JSON.stringify(chunks[loaded].path),
      ]),
    ),
  );
  const measured = measureWidget(text);
  chunkBytes[name] = text;
  chunks[name] = {
    path: `/support-widget/${name}-${sha256(text).slice(0, 16)}.js`,
    sha256: sha256(text),
    sha384: sha384(text),
    ...measured,
  };
}
// The published exports, the build id the widget sends and the chunks it
// loads; Next and vitest bundles report "dev" and bundle the chunks.
const bytes = await bundle(
  readFileSync(`${lib}support-widget-public.ts`, "utf8"),
  {
    __TEMPL_WIDGET_BUILD__: JSON.stringify(digest.slice(0, 16)),
    __TEMPL_WIDGET_CONTEXT__: JSON.stringify(chunks.snapshot.path),
    __TEMPL_WIDGET_EXTRAS__: JSON.stringify(chunks.extras.path),
    __TEMPL_WIDGET_EVM__: JSON.stringify(chunks.evm.path),
    __TEMPL_WIDGET_SOLANA__: JSON.stringify(chunks.solana.path),
    __TEMPL_WIDGET_LIVE__: JSON.stringify(chunks.live.path),
    __TEMPL_WIDGET_DOMAIN__: JSON.stringify(chunks.domain.path),
    __TEMPL_WIDGET_CONSENT__: JSON.stringify(chunks.consent.path),
    __TEMPL_WIDGET_STYLE__: JSON.stringify(chunks.style.path),
    __TEMPL_WIDGET_APPEARANCE__: JSON.stringify(chunks.appearance.path),
    __TEMPL_WIDGET_DRAFTS__: JSON.stringify(chunks.drafts.path),
    __TEMPL_WIDGET_ART__: JSON.stringify(chunks.art.path),
    __TEMPL_WIDGET_LEAD__: JSON.stringify(chunks.lead.path),
  },
  `// Templ support widget. Source SHA-256: ${digest}`,
);
const size = measureWidget(bytes);
const id = sha256(bytes).slice(0, 16);
// Frame mode, built after the core it runs. `frame` is
// the adapter Templ's frame document loads with this core's path; the
// `framehost` file is what a protocol page loads in place of the widget,
// naming this build, and it loads `framebridge` (the page's side of the
// frame's wallet calls) on the first call.
for (const [name, contents, define] of [
  [
    "frame",
    'import { startFrame } from "./support-widget-frame"; startFrame();',
    {
      __TEMPL_FRAME_CORE__: JSON.stringify(`/support-widget/${id}.js`),
      __TEMPL_WIDGET_DRAFTS__: JSON.stringify(chunks.drafts.path),
    },
  ],
  [
    "framebridge",
    'export { bridge } from "./support-widget-frame-bridge";',
    {},
  ],
  [
    "framehost",
    'export { mountSupportWidget } from "./support-widget-frame-host";',
    {
      __TEMPL_FRAME_BUILD__: JSON.stringify(id),
      __TEMPL_FRAME_BRIDGE__: "FRAMEBRIDGE",
      __TEMPL_FRAME_GUEST__: JSON.stringify(chunks.guest.path),
      __TEMPL_WIDGET_APPEARANCE__: JSON.stringify(chunks.appearance.path),
      __TEMPL_WIDGET_ART__: JSON.stringify(chunks.art.path),
    },
  ],
]) {
  if (define.__TEMPL_FRAME_BRIDGE__)
    define.__TEMPL_FRAME_BRIDGE__ = JSON.stringify(chunks.framebridge.path);
  const text = await bundle(contents, define);
  chunkBytes[name] = text;
  chunks[name] = {
    path: `/support-widget/${name}-${sha256(text).slice(0, 16)}.js`,
    sha256: sha256(text),
    sha384: sha384(text),
    ...measureWidget(text),
  };
}
if (
  Object.keys(chunks).join() !== WIDGET_CHUNKS.join() ||
  Object.values(chunks).some((chunk) => !chunk)
)
  throw new Error(`Build the chunks ${WIDGET_CHUNKS.join(", ")}.`);
const report = (chunk) => ({
  bytes: chunk.bytes,
  gzipBytes: chunk.gzipBytes,
  budget: WIDGET_CHUNK_BUDGET,
});
console.log(
  JSON.stringify({
    widget: { ...size, budget: WIDGET_BUDGET },
    ...Object.fromEntries(
      WIDGET_CHUNKS.map((name) => [name, report(chunks[name])]),
    ),
  }),
);
assertWidgetBudget(size);
for (const [name, chunk] of Object.entries(chunks))
  assertWidgetBudget(chunk, WIDGET_CHUNK_BUDGET, `The ${name} chunk`);

if (process.argv.includes("--measure")) process.exit(0);

const current = {
  id,
  path: `/support-widget/${id}.js`,
  sha256: sha256(bytes),
  sha384: sha384(bytes),
  sourceSha256: digest,
  ...size,
  chunks,
};
let manifest = existsSync(manifestPath)
  ? JSON.parse(readFileSync(manifestPath, "utf8"))
  : {
      schemaVersion: 1,
      supportDays: WIDGET_SUPPORT_DAYS,
      latest: null,
      versions: [],
    };
const files = () =>
  new Map(
    (existsSync(versionsDir) ? readdirSync(versionsDir) : []).map((name) => [
      name,
      sha256(readFileSync(`${versionsDir}${name}`)),
    ]),
  );

if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== bytes)
    throw new Error("Rebuild support-widget.js before deploying.");
  if (readFileSync(typesTarget, "utf8") !== types)
    throw new Error("Rebuild support-widget.d.ts before deploying.");
  const latest = manifest.versions.find(
    (version) => version.id === manifest.latest,
  );
  if (
    JSON.stringify(Object.entries(current).map(([key]) => latest?.[key])) !==
    JSON.stringify(Object.values(current))
  )
    throw new Error(
      "Rebuild support-widget.js: the manifest names another build.",
    );
} else {
  const today = new Date().toISOString().slice(0, 10);
  const remove = [];
  if (process.argv.includes("--prune")) {
    // Run in a commit made for that purpose, never in CI.
    const pruned = pruneWidgetBuilds(manifest, today);
    manifest = pruned.manifest;
    remove.push(...pruned.remove);
  }
  const added = addWidgetBuild(manifest, current, today);
  manifest = added.manifest;
  remove.push(...added.remove);
  for (const name of remove) rmSync(`${versionsDir}${name}`, { force: true });
  mkdirSync(versionsDir, { recursive: true });
  writeFileSync(target, bytes);
  writeFileSync(typesTarget, types);
  writeFileSync(`${versionsDir}${id}.js`, bytes);
  for (const [name, chunk] of Object.entries(chunks))
    writeFileSync(
      `${versionsDir}${chunk.path.split("/").pop()}`,
      chunkBytes[name],
    );
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
}
const problem = widgetManifestProblem(manifest, files());
if (problem) throw new Error(problem);
